def hname(sym: str) -> str:
    """מחזיר 'שם · נ"ע מספר' או הטיקר אם אין מיפוי."""
    name = HEBREW_NAMES.get(sym)
    secn = SEC_NUMBERS.get(sym)
    if name and secn:
        return f'{name} · נ"ע {secn}'
    if name:
        return f"{name} ({sym})"
    return sym


def sec_number(sym: str) -> str | None:
    return SEC_NUMBERS.get(sym)
